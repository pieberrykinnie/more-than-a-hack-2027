"""One module per idea. The loop runs any of them by name, on the practice set or on the match.

Each module exposes:

    DEFAULTS = {"param": value, ...}          every tunable, with the value submit uses by default
    def predict(match, **params) -> codes     (n_frames,) int8 in possession_metrics codes H/A/D/X

predict sees a possession.match.Match and nothing else -- no labels, no file paths -- so the same
call scores on a practice game and writes the submission. It must be deterministic: the
submission has to be regenerated byte for byte (RULES.md). Seed anything random from params.

To add an idea: copy nearest.py, register it below, run `python -m possession.dev <name>`.
"""

import importlib

# Params
REGISTRY = (
    "nearest",
)


def get(name):
    if name not in REGISTRY:
        raise KeyError("no approach {!r}; have {}".format(name, ", ".join(REGISTRY)))
    return importlib.import_module("possession.approaches." + name)


def resolve(module, overrides):
    """DEFAULTS updated by k=v strings from the command line, each cast to the default's type."""
    params = dict(module.DEFAULTS)
    for item in overrides:
        key, sep, value = item.partition("=")
        if not sep or key not in params:
            raise KeyError("{!r}: expected key=value with key in {}".format(item, sorted(params)))
        default = params[key]
        if isinstance(default, bool):
            params[key] = value.lower() in ("1", "true", "yes")
        elif default is None:
            params[key] = value
        else:
            params[key] = type(default)(value)
    return params
